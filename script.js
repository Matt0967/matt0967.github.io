function getNestedValue(object, path) {
    return path.split('.').reduce((currentValue, key) => currentValue?.[key], object);
}

let portfolioData = null;

function getLocalizedValue(value, language) {
    if (typeof value === 'string') {
        return value;
    }

    if (value && typeof value === 'object') {
        return value[language] || value.fr || value.en || Object.values(value)[0] || '';
    }

    return '';
}

function createTextElement(tagName, className, text) {
    const element = document.createElement(tagName);

    if (className) {
        element.className = className;
    }

    element.textContent = text;
    return element;
}

function renderProjects(language) {
    const timeline = document.querySelector('#experience .timeline');

    if (!timeline || !Array.isArray(portfolioData?.projects)) {
        return;
    }

    timeline.replaceChildren();

    portfolioData.projects.forEach((project) => {
        const item = document.createElement('div');
        item.className = 'timeline-item';

        const date = createTextElement('div', 'timeline-date', getLocalizedValue(project.date, language));
        const content = document.createElement('div');
        content.className = 'timeline-content';

        content.append(
            createTextElement('h3', '', getLocalizedValue(project.title, language)),
            createTextElement('p', 'role', getLocalizedValue(project.role, language)),
            createTextElement('p', 'description', getLocalizedValue(project.description, language))
        );

        if (project.tech?.length) {
            const techStack = document.createElement('div');
            techStack.className = 'tech-stack';

            project.tech.forEach((tech) => {
                techStack.append(createTextElement('span', '', getLocalizedValue(tech, language)));
            });

            content.append(techStack);
        }

        item.append(date, content);
        timeline.append(item);
    });
}

function renderSkills(language) {
    const skillsGrid = document.querySelector('#skills .skills-grid');

    if (!skillsGrid || !Array.isArray(portfolioData?.skills)) {
        return;
    }

    skillsGrid.replaceChildren();

    portfolioData.skills.forEach((category) => {
        const categoryElement = document.createElement('div');
        categoryElement.className = 'skill-category';
        categoryElement.append(createTextElement('h3', '', getLocalizedValue(category.title, language)));

        const list = document.createElement('ul');

        category.items?.forEach((skill) => {
            list.append(createTextElement('li', '', getLocalizedValue(skill, language)));
        });

        categoryElement.append(list);
        skillsGrid.append(categoryElement);
    });
}

function renderInterests(language) {
    const interestsList = document.querySelector('#interests .interests-list');

    if (!interestsList || !Array.isArray(portfolioData?.interests)) {
        return;
    }

    interestsList.replaceChildren();

    portfolioData.interests.forEach((interest) => {
        interestsList.append(createTextElement('li', '', getLocalizedValue(interest.label, language)));
    });
}

function renderEducation(language) {
    const educationList = document.querySelector('#education .education-list');

    if (!educationList || !Array.isArray(portfolioData?.education)) {
        return;
    }

    educationList.replaceChildren();

    portfolioData.education.forEach((educationItem) => {
        const item = document.createElement('div');
        item.className = 'education-item';

        item.append(
            createTextElement('h3', '', getLocalizedValue(educationItem.title, language)),
            createTextElement('p', 'school', getLocalizedValue(educationItem.school, language)),
            createTextElement('p', 'year', educationItem.year || '')
        );

        educationList.append(item);
    });
}

function renderLanguages(language) {
    const languagesContainer = document.querySelector('#languages .languages');

    if (!languagesContainer || !Array.isArray(portfolioData?.languages)) {
        return;
    }

    languagesContainer.replaceChildren();

    portfolioData.languages.forEach((spokenLanguage) => {
        const wrapper = document.createElement('span');
        wrapper.className = 'language';

        wrapper.append(
            createTextElement('strong', '', getLocalizedValue(spokenLanguage.label, language)),
            createTextElement('span', '', ` - ${getLocalizedValue(spokenLanguage.level, language)}`)
        );

        languagesContainer.append(wrapper);
    });
}

function renderContact(language) {
    const contactMount = document.getElementById('contactFormMount');

    if (!contactMount) {
        return;
    }

    const formUrl = portfolioData?.contact?.notionFormUrl?.trim();
    contactMount.replaceChildren();

    if (!formUrl) {
        contactMount.append(createTextElement('p', 'contact-form-placeholder', translations[language]?.contact?.formPlaceholder || translations.fr.contact.formPlaceholder));
        return;
    }

    try {
        const url = new URL(formUrl);

        if (url.protocol !== 'https:') {
            throw new Error('Only HTTPS form URLs are supported.');
        }

        const title = createTextElement('p', 'contact-form-heading', getLocalizedValue(portfolioData.contact?.iframeTitle, language) || 'Formulaire de contact Notion');
        const actionLink = createTextElement('a', 'contact-form-action', getLocalizedValue(portfolioData.contact?.openLabel, language) || 'Ouvrir le formulaire Notion');
        actionLink.href = url.href;
        actionLink.target = '_blank';
        actionLink.rel = 'noopener noreferrer';

        contactMount.append(title, actionLink);
    } catch (error) {
        contactMount.append(createTextElement('p', 'contact-form-placeholder', translations[language]?.contact?.formPlaceholder || translations.fr.contact.formPlaceholder));
    }
}

function renderPortfolioSections(language) {
    renderProjects(language);
    renderSkills(language);
    renderInterests(language);
    renderEducation(language);
    renderLanguages(language);
    renderContact(language);
}

async function loadPortfolioData() {
    try {
        const response = await fetch('portfolio-data.json', { cache: 'no-cache' });

        if (!response.ok) {
            throw new Error(`portfolio-data.json returned ${response.status}`);
        }

        portfolioData = await response.json();
    } catch (error) {
        console.warn('Impossible de charger portfolio-data.json. Le contenu HTML statique reste affiché.', error);
    }
}

const ACCESSIBILITY_STORAGE_KEY = 'accessibilitySettings';
const DEFAULT_ACCESSIBILITY_SETTINGS = {
    textSize: 'normal',
    highContrast: false,
    reduceMotion: false,
    underlineLinks: false,
    readableFont: false,
    comfortableSpacing: false
};

function prefersReducedMotion() {
    return window.matchMedia('(prefers-reduced-motion: reduce)').matches;
}

document.addEventListener('DOMContentLoaded', () => {
    const themeToggle = document.getElementById('themeToggle');
    const languageSwitcher = document.getElementById('languageSwitcher');
    const accessibilityMenu = document.getElementById('accessibilityMenu');
    const accessibilityToggle = document.getElementById('accessibilityToggle');
    const accessibilityPanel = document.getElementById('accessibilityPanel');
    const accessibilityClose = document.getElementById('accessibilityClose');
    const accessibilityReset = document.getElementById('accessibilityReset');
    const textSizeButtons = document.querySelectorAll('[data-a11y-text-option]');
    const contrastToggle = document.getElementById('contrastToggle');
    const motionToggle = document.getElementById('motionToggle');
    const linksToggle = document.getElementById('linksToggle');
    const fontToggle = document.getElementById('fontToggle');
    const spacingToggle = document.getElementById('spacingToggle');
    const logo = document.querySelector('.logo');
    const navbar = document.querySelector('.navbar');
    let itemObserver = null;
    let accessibilitySettings = readAccessibilitySettings();

    function updateNavbarBackground() {
        const rootStyles = getComputedStyle(document.documentElement);
        const backgroundVariable = window.scrollY > 50 ? '--navbar-bg-scrolled' : '--navbar-bg';
        navbar.style.background = rootStyles.getPropertyValue(backgroundVariable).trim();
    }

    // Le thème reste piloté par des variables CSS, pour que JS ne duplique pas la logique visuelle.
    function applyTheme(theme) {
        if (theme === 'color') {
            document.documentElement.setAttribute('data-theme', 'color');
        } else {
            document.documentElement.removeAttribute('data-theme');
        }

        localStorage.setItem('theme', theme);
        updateNavbarBackground();
    }

    function readAccessibilitySettings() {
        try {
            const savedSettings = JSON.parse(localStorage.getItem(ACCESSIBILITY_STORAGE_KEY));

            return {
                ...DEFAULT_ACCESSIBILITY_SETTINGS,
                ...(savedSettings && typeof savedSettings === 'object' ? savedSettings : {})
            };
        } catch (error) {
            return { ...DEFAULT_ACCESSIBILITY_SETTINGS };
        }
    }

    function setRootAttribute(attributeName, value, defaultValue) {
        if (value && value !== defaultValue) {
            document.documentElement.setAttribute(attributeName, value);
        } else {
            document.documentElement.removeAttribute(attributeName);
        }
    }

    function updateAccessibilityControls() {
        textSizeButtons.forEach((button) => {
            const isActive = button.dataset.a11yTextOption === accessibilitySettings.textSize;
            button.setAttribute('aria-pressed', String(isActive));
        });

        if (contrastToggle) {
            contrastToggle.checked = accessibilitySettings.highContrast;
        }

        if (motionToggle) {
            motionToggle.checked = accessibilitySettings.reduceMotion;
        }

        if (linksToggle) {
            linksToggle.checked = accessibilitySettings.underlineLinks;
        }

        if (fontToggle) {
            fontToggle.checked = accessibilitySettings.readableFont;
        }

        if (spacingToggle) {
            spacingToggle.checked = accessibilitySettings.comfortableSpacing;
        }
    }

    function applyAccessibility(nextSettings, shouldPersist = true) {
        accessibilitySettings = {
            ...DEFAULT_ACCESSIBILITY_SETTINGS,
            ...nextSettings,
            textSize: ['normal', 'large', 'xlarge'].includes(nextSettings.textSize) ? nextSettings.textSize : 'normal'
        };

        setRootAttribute('data-a11y-text', accessibilitySettings.textSize, 'normal');
        setRootAttribute('data-a11y-contrast', accessibilitySettings.highContrast ? 'high' : '', '');
        setRootAttribute('data-a11y-motion', accessibilitySettings.reduceMotion ? 'reduced' : '', '');
        setRootAttribute('data-a11y-links', accessibilitySettings.underlineLinks ? 'underlined' : '', '');
        setRootAttribute('data-a11y-font', accessibilitySettings.readableFont ? 'system' : '', '');
        setRootAttribute('data-a11y-spacing', accessibilitySettings.comfortableSpacing ? 'comfortable' : '', '');

        updateAccessibilityControls();

        if (shouldPersist) {
            localStorage.setItem(ACCESSIBILITY_STORAGE_KEY, JSON.stringify(accessibilitySettings));
        }

        updateNavbarBackground();
    }

    function setAccessibilityPanelOpen(isOpen) {
        if (!accessibilityPanel || !accessibilityToggle) {
            return;
        }

        accessibilityPanel.hidden = !isOpen;
        accessibilityToggle.setAttribute('aria-expanded', String(isOpen));

        if (isOpen) {
            const firstControl = accessibilityPanel.querySelector('button, input, select, textarea, a[href]');
            firstControl?.focus();
        } else if (document.activeElement && accessibilityPanel.contains(document.activeElement)) {
            accessibilityToggle.focus();
        }
    }

    function shouldUseReducedMotion() {
        return accessibilitySettings.reduceMotion || prefersReducedMotion();
    }

    function triggerEasterEgg() {
        document.querySelector('.easter-egg-terminal')?.remove();

        const currentLanguage = translations[document.documentElement.lang] ? document.documentElement.lang : 'fr';
        const copy = translations[currentLanguage].easterEgg || translations.fr.easterEgg;
        const terminal = document.createElement('div');
        terminal.className = 'easter-egg-terminal';
        terminal.setAttribute('role', 'status');
        terminal.setAttribute('aria-live', 'polite');

        const title = createTextElement('p', 'easter-egg-title', copy.title);
        const lines = document.createElement('div');
        lines.className = 'easter-egg-lines';

        copy.lines.forEach((line) => {
            lines.append(createTextElement('span', '', line));
        });

        const progress = document.createElement('div');
        progress.className = 'easter-egg-progress';

        const circuit = document.createElement('div');
        circuit.className = 'easter-egg-circuit';

        for (let index = 0; index < 5; index += 1) {
            circuit.append(document.createElement('i'));
        }

        terminal.append(title, lines, progress, circuit);
        document.body.append(terminal);

        window.setTimeout(() => {
            terminal.remove();
        }, shouldUseReducedMotion() ? 2600 : 5200);
    }

    // Tous les textes passent par data-i18n, ce qui évite de disperser les chaînes dans le HTML et le JS.
    function applyLanguage(language) {
        const selectedLanguage = translations[language] ? language : 'fr';
        const copy = translations[selectedLanguage];

        document.documentElement.lang = selectedLanguage;
        document.title = copy.meta.title;
        themeToggle.setAttribute('aria-label', copy.meta.themeToggleAria);
        languageSwitcher.setAttribute('aria-label', copy.meta.languageSwitcherAria);
        accessibilityToggle?.setAttribute('aria-label', copy.meta.accessibilityToggleAria);
        accessibilityClose?.setAttribute('aria-label', copy.meta.accessibilityCloseAria);

        document.querySelectorAll('[data-i18n]').forEach((element) => {
            const key = element.dataset.i18n;
            const translatedText = getNestedValue(copy, key);

            if (translatedText) {
                element.textContent = translatedText;
            }
        });

        languageSwitcher.value = selectedLanguage;
        localStorage.setItem('language', selectedLanguage);
        renderPortfolioSections(selectedLanguage);
        observeAnimatedItems();
    }

    function observeAnimatedItems() {
        if (!itemObserver) {
            return;
        }

        const animatedGroups = [
            { selector: '.timeline-item', delay: 100 },
            { selector: '.skill-category', delay: 100 },
            { selector: '.interests-list li', delay: 100 },
            { selector: '.education-item', delay: 150 },
            { selector: '.language', delay: 100 },
            { selector: '.contact-form-card', delay: 150 }
        ];

        animatedGroups.forEach(({ selector, delay }) => {
            document.querySelectorAll(selector).forEach((element, index) => {
                element.style.transitionDelay = `${index * (delay / 1000)}s`;
                itemObserver.observe(element);

                if (element.closest('.section.visible')) {
                    element.classList.add('visible');
                }
            });
        });
    }

    const savedTheme = localStorage.getItem('theme');
    const savedLanguage = localStorage.getItem('language');

    applyTheme(savedTheme === 'color' ? 'color' : 'dark');
    applyAccessibility(accessibilitySettings, false);
    applyLanguage(savedLanguage || 'fr');
    loadPortfolioData().then(() => {
        applyLanguage(localStorage.getItem('language') || savedLanguage || 'fr');
    });

    themeToggle.addEventListener('click', () => {
        const currentTheme = document.documentElement.getAttribute('data-theme');
        applyTheme(currentTheme === 'color' ? 'dark' : 'color');
    });

    languageSwitcher.addEventListener('change', (event) => {
        applyLanguage(event.target.value);
    });

    accessibilityToggle?.addEventListener('click', (event) => {
        event.stopPropagation();
        setAccessibilityPanelOpen(accessibilityPanel?.hidden ?? true);
    });

    accessibilityClose?.addEventListener('click', () => {
        setAccessibilityPanelOpen(false);
    });

    textSizeButtons.forEach((button) => {
        button.addEventListener('click', () => {
            applyAccessibility({
                ...accessibilitySettings,
                textSize: button.dataset.a11yTextOption || 'normal'
            });
        });
    });

    contrastToggle?.addEventListener('change', (event) => {
        applyAccessibility({
            ...accessibilitySettings,
            highContrast: event.target.checked
        });
    });

    motionToggle?.addEventListener('change', (event) => {
        applyAccessibility({
            ...accessibilitySettings,
            reduceMotion: event.target.checked
        });
    });

    linksToggle?.addEventListener('change', (event) => {
        applyAccessibility({
            ...accessibilitySettings,
            underlineLinks: event.target.checked
        });
    });

    fontToggle?.addEventListener('change', (event) => {
        applyAccessibility({
            ...accessibilitySettings,
            readableFont: event.target.checked
        });
    });

    spacingToggle?.addEventListener('change', (event) => {
        applyAccessibility({
            ...accessibilitySettings,
            comfortableSpacing: event.target.checked
        });
    });

    accessibilityReset?.addEventListener('click', () => {
        applyAccessibility({ ...DEFAULT_ACCESSIBILITY_SETTINGS });
    });

    document.addEventListener('click', (event) => {
        if (!accessibilityPanel?.hidden && accessibilityMenu && !accessibilityMenu.contains(event.target)) {
            setAccessibilityPanelOpen(false);
        }
    });

    document.addEventListener('keydown', (event) => {
        if (event.key === 'Escape' && !accessibilityPanel?.hidden) {
            setAccessibilityPanelOpen(false);
        }
    });

    window.addEventListener('scroll', updateNavbarBackground);

    document.querySelectorAll('a[href^="#"]').forEach((anchor) => {
        anchor.addEventListener('click', function(e) {
            e.preventDefault();
            const targetSelector = this.getAttribute('href');

            if (targetSelector === '#') {
                window.scrollTo({
                    top: 0,
                    behavior: shouldUseReducedMotion() ? 'auto' : 'smooth'
                });
                return;
            }

            const target = document.querySelector(targetSelector);

            if (target) {
                target.scrollIntoView({
                    behavior: shouldUseReducedMotion() ? 'auto' : 'smooth',
                    block: 'start'
                });
            }
        });
    });

    let easterEggClicks = 0;
    let easterEggTimer = null;

    logo?.addEventListener('click', () => {
        easterEggClicks += 1;
        window.clearTimeout(easterEggTimer);

        if (easterEggClicks >= 10) {
            easterEggClicks = 0;
            triggerEasterEgg();
            return;
        }

        easterEggTimer = window.setTimeout(() => {
            easterEggClicks = 0;
        }, 2500);
    });

    const observerOptions = {
        root: null,
        rootMargin: '0px',
        threshold: 0.1
    };

    const sectionObserver = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
            }
        });
    }, observerOptions);

    document.querySelectorAll('.section').forEach((section) => {
        sectionObserver.observe(section);
    });

    itemObserver = new IntersectionObserver((entries) => {
        entries.forEach((entry, index) => {
            if (entry.isIntersecting) {
                setTimeout(() => {
                    entry.target.classList.add('visible');
                }, index * 100);
            }
        });
    }, observerOptions);

    observeAnimatedItems();

    const heroContent = document.querySelector('.hero-content');
    heroContent.style.opacity = '1';
    heroContent.style.transform = 'none';
});

document.addEventListener('mousemove', (e) => {
    if (document.documentElement.getAttribute('data-a11y-motion') === 'reduced' || prefersReducedMotion()) {
        document.querySelector('.cursor-glow')?.remove();
        return;
    }

    let glow = document.querySelector('.cursor-glow');

    if (!glow) {
        glow = document.createElement('div');
        glow.className = 'cursor-glow';
        document.body.appendChild(glow);
    }

    glow.style.left = `${e.clientX - 200}px`;
    glow.style.top = `${e.clientY - 200}px`;
});
